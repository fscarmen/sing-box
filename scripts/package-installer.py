#!/usr/bin/env python3
"""Build a single uploadable installer from an explicit, non-secret source list."""
import base64
import hashlib
import gzip
import io
import tarfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / 'outputs/sing-box-dashboard-installer.sh'
TOP = ('bootstrap.sh', 'sing-box.sh', 'LICENSE', 'README.md', 'BOOTSTRAP.md',
       'docs/FIXED-SUBSCRIPTION.md', 'docs/XRAY-MONITOR.md', 'docs/XRAY-DEPLOY.md', 'docs/CLIENT-RULES.md',
       'dashboard/deploy/xray-stats.example.json')
TREES = ('dashboard/panel', 'dashboard/static', 'dashboard/vendor/xray-install')
FILES = ('dashboard/app.py', 'dashboard/manager.py', 'dashboard/panel-firewall.sh',
         'dashboard/admin.py', 'dashboard/core_download.py', 'dashboard/subscription_server.py', 'dashboard/requirements.lock', 'dashboard/UPSTREAM.md')
FILES += ('dashboard/xray_manager.py', 'dashboard/xray_download.py', 'dashboard/xray_firewall.py')
buffer = io.BytesIO()
with gzip.GzipFile(fileobj=buffer, mode='wb', mtime=0) as compressed, tarfile.open(fileobj=compressed, mode='w') as tar:
    paths = [ROOT / p for p in TOP + FILES]
    for tree in TREES:
        paths.extend(p for p in (ROOT / tree).rglob('*') if p.is_file() and '__pycache__' not in p.parts and p.suffix != '.pyc')
    for path in sorted(paths):
        if path.is_symlink():
            raise SystemExit('Refusing symlink: ' + str(path))
        info = tar.gettarinfo(str(path), arcname=str(path.relative_to(ROOT)))
        info.uid = info.gid = info.mtime = 0
        info.uname = info.gname = ''
        info.mode = 0o755 if path.suffix == '.sh' else 0o644
        with path.open('rb') as source:
            tar.addfile(info, source)
archive = buffer.getvalue()
digest = hashlib.sha256(archive).hexdigest()
header = '''#!/usr/bin/env bash
# Generated by scripts/package-installer.py. Contains only the allowlisted sources.
set -Eeuo pipefail
umask 077
SB_EXTRACT=$(mktemp -d /tmp/sb-installer.XXXXXX)
trap 'rm -rf -- "$SB_EXTRACT"' EXIT
sed '1,/^__SB_PAYLOAD__$/d' "$0" | base64 --decode > "$SB_EXTRACT/source.tgz"
printf '%s  %s\\n' 'DIGEST' "$SB_EXTRACT/source.tgz" | sha256sum --check --status
tar -xzf "$SB_EXTRACT/source.tgz" -C "$SB_EXTRACT" --no-same-owner
bash "$SB_EXTRACT/bootstrap.sh" --source-dir "$SB_EXTRACT" "$@"
exit 0
__SB_PAYLOAD__
'''.replace('DIGEST', digest)
OUTPUT.parent.mkdir(exist_ok=True)
OUTPUT.write_text(header + base64.encodebytes(archive).decode())
OUTPUT.chmod(0o755)
OUTPUT.with_suffix('.sha256').write_text(hashlib.sha256(OUTPUT.read_bytes()).hexdigest() + '  ' + OUTPUT.name + '\n')
print(str(OUTPUT))
print('Embedded source SHA256: ' + digest)
